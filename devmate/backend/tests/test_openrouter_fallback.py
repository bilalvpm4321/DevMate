"""Unit tests verifying intelligent OpenRouter fallback upon Gemini rate limits or failures."""
import dataclasses
import pytest

from app.services import llm


@pytest.mark.anyio
async def test_openrouter_fallback_on_gemini_429(monkeypatch):
    mock_settings = dataclasses.replace(
        llm.settings,
        gemini_api_key="test-gemini-key",
        openrouter_api_key="test-openrouter-key",
        openrouter_model="google/gemini-2.5-flash",
    )
    monkeypatch.setattr(llm, "settings", mock_settings)

    # Mock _call_gemini to simulate a 429 Rate Limit error
    async def mock_call_gemini(*args, **kwargs):
        return 429, "", "Quota exceeded / ResourceExhausted for model"

    # Mock _call_openrouter to simulate successful failover
    async def mock_call_openrouter(*args, **kwargs):
        return 200, "Answer generated by OpenRouter fallback", ""

    monkeypatch.setattr(llm, "_call_gemini", mock_call_gemini)
    monkeypatch.setattr(llm, "_call_openrouter", mock_call_openrouter)

    reply = await llm.generate("You are DevMate.", "Explain recursion in 1 line.")
    assert reply == "Answer generated by OpenRouter fallback"


